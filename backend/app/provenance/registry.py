def mola_record(meta: dict, steps: list, synthetic: bool, kind: str = "topography") -> dict:
    tile = MOLA_TOPO_TILE if kind == "topography" else MOLA_COUNT_TILE
    r = meta.get("radius_m", 3396000.0)
    ppd = meta.get("ppd", 128)
    rec = {
        "id": f"mola_{kind}",
        "source_name": "MGS MOLA Mission Experiment Gridded Data Record (MEGDR), 128 px/deg",
        "mission": "Mars Global Surveyor (NASA)",
        "instrument": "MOLA — Mars Orbiter Laser Altimeter",
        "product": f"{tile} — "
        + ("topography relative to the MOLA areoid (m)" if kind == "topography" else "number of MOLA shots per bin"),
        "source_url": PDS_MEG128 + tile + ".img",
        "archive": "NASA Planetary Data System, Geosciences Node — bundle mgs_mola_topography_derived "
        "(PDS3 data set MGS-M-MOLA-5-MEGDR-L3-V1.0, DOI 10.17189/1519460)",
        "spatial_reference": f"Simple cylindrical; planetocentric latitude, east-positive longitude; sphere R = {r/1000:.1f} km",
        "coverage": meta.get("extent"),
        "resolution": f"1/{ppd:g}° per pixel ≈ {3.141592653589793 * r / 180 / ppd:.0f} m (north-south)",
        "retrieval_date": meta.get("retrieved", str(date.today())),
        "processing_steps": steps,
        "credit": "NASA / GSFC MOLA Science Team / PDS Geosciences Node",
        "notes": "MEGDR bins MOLA nadir shots (Feb 1999 – Jun 2001). Per the product label: where no observations lie in a bin an interpolated value is supplied; near the equator about 55% of bins contain at least one shot, with gaps of up to 12 km between profiles.",
        "limitations": [
            "~463 m cells: boulders, small craters, ripples and slopes shorter than ~1 km are not resolved",
            "Bins with zero MOLA shots are interpolated (label: up to 12 km between profiles)",
            "Heights are relative to the MOLA areoid",
        ],
        "status": "SYNTHETIC" if synthetic else "VERIFIED",
    }
    if synthetic:  # never let a synthetic tile carry a real archive identity
        rec.update(
            {
                "source_name": "SYNTHETIC TEST FIXTURE in MOLA MEGDR binary format — NOT NASA DATA",
                "mission": "none (synthetic)",
                "instrument": "none — file layout mimics MOLA MEGDR",
                "product": f"meg{'t' if kind == 'topography' else 'c'}_fixture — synthetic {kind}",
                "source_url": f"local file data/fixtures/meg{'t' if kind == 'topography' else 'c'}_fixture.img (generated by scripts/make_fixture.py)",
                "archive": "none — synthetic. Real source once fetched: " + PDS_MEG128 + tile + ".img",
                "credit": "MARSCOPE test fixture (not NASA)",
                "notes": "Exercises the pipeline where the PDS archive is unreachable. Load the real tile: python scripts/fetch_mola.py, then scripts/build_region.py",
                "limitations": ["Terrain values are synthetic and carry no scientific meaning"] + rec["limitations"],
            }
        )
    return rec


def derived_record(
    lid,
    name,
    formula,
    inputs,
    unit,
    limitations,
    synthetic=False,
    resolution="same as source",
    spatial_reference="same grid as source (no resampling)",
    steps=None,
):
    return {
        "id": lid,
        "source_name": name,
        "mission": "Derived from the synthetic fixture" if synthetic else "Derived from MOLA",
        "instrument": "MARSCOPE pipeline",
        "product": formula,
        "source_url": "derived — see docs/SCIENTIFIC_METHOD.md",
        "archive": "computed locally",
        "spatial_reference": spatial_reference,
        "coverage": "region of interest",
        "resolution": resolution,
        "retrieval_date": str(date.today()),
        "processing_steps": steps or [formula],
        "credit": "inputs: " + ", ".join(inputs),
        "notes": f"unit: {unit}",
        "limitations": limitations,
        "status": "SYNTHETIC" if synthetic else "DERIVED",
    }


def grid_record(level: dict, synthetic: bool) -> dict:
    """Provenance for an interpolated routing/analysis grid. Never VERIFIED: interpolation is not measurement."""
    return {
        "id": f"grid_{level['level']}",
        "source_name": f"{level['level'].capitalize()} grid {level['cell_deg']} (interpolated)",
        "mission": "Derived from the synthetic fixture" if synthetic else "Derived from MOLA MEGDR",
        "instrument": "MARSCOPE pipeline",
        "product": f"elevation resampled to {level['cell_deg']} for "
        + ("route search" if level["level"] == "routing" else "evidence sampling along routes"),
        "source_url": "derived — backend/app/geospatial/levels.py",
        "archive": "computed locally at start-up (not shipped)",
        "spatial_reference": "Simple cylindrical lat/lon grid, same outer bounds as the native clipped grid",
        "coverage": "region of interest",
        "resolution": f"{level['cell_deg']} ≈ {level['cell_ns_m']:.0f} m N-S × {level['cell_ew_m']:.0f} m E-W",
        "retrieval_date": str(date.today()),
        "processing_steps": [level["method"], f"relief window {level['relief_window']}"],
        "credit": "input: native 1/128° grid",
        "notes": level["information_note"],
        "limitations": [
            "Interpolation does not add real terrain detail; effective resolution stays ~463 m",
            "Cubic splines can overshoot near sharp breaks, so fine-grid maximum slopes can exceed native ones",
            "Slope limit (exclusion) is an ASSUMPTION applied unchanged at every grid spacing",
        ],
        "status": "SYNTHETIC" if synthetic else "APPROXIMATE",
    }


